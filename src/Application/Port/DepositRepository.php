namespace TheBeardedBear\UrssafDpae\Application\Port;

use TheBeardedBear\UrssafDpae\Domain\Deposit\Deposit;
use TheBeardedBear\UrssafDpae\Domain\Deposit\DepositId;
use TheBeardedBear\UrssafDpae\Domain\Deposit\ExternalReference;
use TheBeardedBear\UrssafDpae\Domain\Deposit\FlowFingerprint;
use TheBeardedBear\UrssafDpae\Domain\Deposit\FlowId;
use TheBeardedBear\UrssafDpae\Domain\Exception\ConcurrentModification;
use TheBeardedBear\UrssafDpae\Domain\Exception\RecordNotFound;
use TheBeardedBear\UrssafDpae\Domain\Shared\Instant;
use TheBeardedBear\UrssafDpae\Domain\Tenant\TenantId;

/**
 * Persistence of deposits (ADR 0008). Every lookup is scoped by tenant; an implementation backed by a database enforces
 * the uniqueness of the open deposits per `(tenant, external reference)` and `(tenant, fingerprint)` itself.
 */
interface DepositRepository
{
    /**
     * Stores the deposit under optimistic locking: the save succeeds only if the stored version is
     * {@see Deposit::version()}, and then moves the aggregate to the next version with {@see Deposit::advanceVersion()}.
     * The first save of a new deposit counts as one. A conditional {@see self::claim()} also moves the stored version, so a
     * deposit read before a claim cannot overwrite it. A Doctrine adapter maps this on a version column
     * (ADR 0008).
     *
     * @throws ConcurrentModification `deposit.concurrent_modification`: the stored deposit changed since it was read;
     *                                reload it and decide again
     */
    public function save(Deposit $deposit): void;

    /**
     * Not scoped by tenant: a deposit id is generated by the package and only ever reached through a tenant-scoped
     * read or through the id the caller was given, never from user input.
     *
     * @throws RecordNotFound `deposit.not_found`
     */
    public function get(DepositId $id): Deposit;

    /**
     * The open deposit of the tenant for the reference, if any (ADR 0005).
     */
    public function findOpenByReference(TenantId $tenantId, ExternalReference $reference): ?Deposit;

    /**
     * The open deposit of the tenant for the flow, if any (ADR 0005).
     */
    public function findOpenByFingerprint(TenantId $tenantId, FlowFingerprint $fingerprint): ?Deposit;

    /**
     * The deposit of the tenant that holds the flow id, whatever its state.
     */
    public function findByFlowId(TenantId $tenantId, FlowId $flowId): ?Deposit;

    /**
     * Atomic conditional claim: moves a `pending` deposit that has fewer than `$maxAttempts` attempts to `depositing`
     * (counting the attempt, recording `$now`, moving the version) and returns true, or returns false when it is in any
     * other state or out of attempts. Precedes every send, so that concurrent workers never send a flow twice (ADR 0005).
     */
    public function claim(DepositId $id, Instant $now, int $maxAttempts): bool;

    /**
     * The tenant's deposits without a known flow id that were sent or may have been: `depositing`, `outcome_unknown`,
     * `received` and `rejected` ones, the oldest claim first, at most `$limit` of them. Input of the reconciliation
     * (ADR 0005).
     *
     * @param positive-int $limit
     *
     * @return list<Deposit>
     */
    public function withoutFlowId(TenantId $tenantId, int $limit): array;

    /**
     * The tenant's `depositing` deposits claimed strictly before the instant (a crash between claim and answer), the
     * oldest claim first, at most `$limit` of them.
     *
     * @param positive-int $limit
     *
     * @return list<Deposit>
     */
    public function staleDepositing(TenantId $tenantId, Instant $claimedBefore, int $limit): array;
}
