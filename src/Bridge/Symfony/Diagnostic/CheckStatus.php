/**
 * Outcome of one installation check; only a failure makes `urssaf:dpae:check` exit with 1.
 */
enum CheckStatus: string
{
    case Ok = 'ok';
    case Warning = 'warning';
    case Failure = 'failure';
    case Skipped = 'skipped';
}
